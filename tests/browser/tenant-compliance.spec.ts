import { test, expect } from '@playwright/test'

test('compliance profile and agreement configuration share the same page shell', async ({ page }) => {
    await page.goto('/tenant-compliance')
    await expect(page.getByRole('heading', { name: '合规配置', exact: true })).toBeVisible()
    await expect(page.getByRole('textbox', { name: '公司主体名称', exact: true })).toHaveValue('Alpha Global Technology Limited')
    await expect(page.getByRole('button', { name: '保存配置', exact: true })).toBeDisabled()
    await page.screenshot({ path: '/tmp/tenant-compliance-profile.png' })
    await page.getByRole('tab', { name: '协议文件', exact: true }).click()
    await expect(page.getByRole('switch')).toHaveCount(5)
    await expect(page.getByRole('textbox', { name: '用户协议链接', exact: true })).toBeVisible()
    await expect(page.getByText('自动同步 20 个章节 · V1', { exact: true })).toBeVisible()
    await page.screenshot({ path: '/tmp/tenant-compliance-agreements.png' })
    await page.getByRole('textbox', { name: '用户协议链接', exact: true }).fill('https://legal.example.com/updated')
    await page.getByRole('button', { name: '保存配置', exact: true }).click()
    await expect(page.locator('.save-status')).toHaveText('已保存')
    await page.getByRole('switch', { name: '用户协议启用', exact: true }).click()
    await page.getByRole('button', { name: '放弃修改', exact: true }).click()
    await expect(page.getByRole('switch', { name: '用户协议启用', exact: true })).toHaveAttribute('aria-checked', 'true')
})
test('readonly compliance settings cannot be edited', async ({ page }) => {
    await page.goto('/tenant-compliance?readonly')
    await expect(page.getByRole('textbox', { name: '公司主体名称', exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: '保存配置', exact: true })).toHaveCount(0)
    await page.getByRole('tab', { name: '协议文件', exact: true }).click()
    for (const toggle of await page.getByRole('switch').all()) await expect(toggle).toBeDisabled()
})
test('uncertain compliance saves are not repeated automatically', async ({ page }) => {
    await page.goto('/tenant-compliance?uncertain')
    await page.getByRole('textbox', { name: '公司主体名称', exact: true }).fill('Changed')
    await page.getByRole('button', { name: '保存配置', exact: true }).click()
    await expect(page.locator('.save-status')).toContainText('保存未确认')
    await expect(page.getByRole('button', { name: '保存配置', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: '重新加载核验', exact: true }).click()
    await page.getByRole('button', { name: '确认重新加载', exact: true }).click()
    await expect(page.getByRole('textbox', { name: '公司主体名称', exact: true })).toHaveValue('Alpha Global Technology Limited')
})
test('compliance settings fit a narrow viewport with a visible save footer', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/tenant-compliance')
    await expect(page.getByRole('textbox', { name: '公司主体名称', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '保存配置', exact: true })).toBeVisible()
    await page.getByRole('tab', { name: '协议文件', exact: true }).click()
    await expect(page.getByRole('textbox', { name: '用户协议链接', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: '/tmp/tenant-compliance-mobile.png' })
})
