import { expect, test } from '@playwright/test'
import { mkdirSync } from 'node:fs'

test('Agent-style SEO page supports explicit save, scoped site switching, manual language drafts and readonly/mobile layouts', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  mkdirSync('/tmp/tenant-seo-qa', { recursive: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/tenant-seo')
  const title = page.getByRole('textbox', { name: '首页标题', exact: true })
  await expect(title).toHaveValue('AlphaEx 首页')
  const save = page.getByRole('button', { name: '保存配置', exact: true })
  await expect(save).toBeDisabled()
  await page.screenshot({ path: '/tmp/tenant-seo-qa/agent-desktop.png', fullPage: true })
  await title.fill('Edited title')
  await page.getByRole('button', { name: '多语言文案', exact: true }).click()
  const languages = page.getByRole('dialog', { name: /多语言 SEO 文案/ })
  await expect(languages.getByRole('button', { name: '翻译配置', exact: true })).toHaveCount(0)
  await page.getByRole('textbox', { name: 'zh-CN 首页标题', exact: true }).fill('Nested draft')
  await languages.getByRole('button', { name: '取消', exact: true }).click()
  await expect(title).toHaveValue('Edited title')
  await page.getByRole('combobox', { name: '配置站点' }).click()
  await page.getByRole('option', { name: '备用站点 · 910002', exact: true }).click()
  const discardDialog = page.getByRole('dialog', { name: '放弃未保存的修改？', exact: true })
  await expect(discardDialog).toBeVisible()
  await discardDialog.getByRole('button', { name: '继续编辑' }).click()
  await expect(title).toHaveValue('Edited title')
  await save.click()
  await expect(save).toBeDisabled()
  await page.getByRole('combobox', { name: '配置站点' }).click()
  await page.getByRole('option', { name: '备用站点 · 910002', exact: true }).click()
  await expect(title).toHaveValue('AlphaEx 首页')
  await page.getByRole('combobox', { name: '配置站点' }).click()
  await page.getByRole('option', { name: '主站 · 910001', exact: true }).click()
  await expect(title).toHaveValue('Edited title')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '/tmp/tenant-seo-qa/agent-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const footer = await page.locator('.mm-tenant-seo-settings__footer').boundingBox()
  expect(footer!.y + footer!.height).toBeLessThanOrEqual(844)
  await page.goto('/tenant-seo?readonly')
  await expect(title).toBeDisabled()
  await expect(page.getByRole('button', { name: '保存配置' })).toHaveCount(0)
  expect(errors).toEqual([])
})
