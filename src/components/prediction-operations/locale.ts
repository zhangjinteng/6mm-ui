export function usePredictionLocale(locale?: () => string | undefined) {
    const presentation = usePresentation(), fallback = useLocale()
    return (value: string): string => {
        if ((locale?.() ?? presentation().locale ?? fallback.locale.value) !== 'en-US') return value
        if (english[value]) return english[value]
        if (/^\d+秒$/.test(value)) return value.replace('秒', 's')
        if (value.includes(' · ')) return value.split(' · ').map(part => english[part] || part).join(' · ')
        if (value.endsWith('：全部')) return (english[value.slice(0,-3)] || value.slice(0,-3)) + ': All'
        if (value.endsWith('（最多31天）')) return (english[value.slice(0,-7)] || value.slice(0,-7)) + ' (up to 31 days)'
        if (value.startsWith('筛选')) return 'Filter ' + (english[value.slice(2)] || value.slice(2))
        return value
    }
}
